set -euo pipefail
cd -- "$(dirname -- "$0")"
if [[ $# != 1 || -z "$1" || "$1" == -* ]]; then
  echo 'Usage: ./install.sh SSH_ALIAS_OR_ROOT_AT_TABLET_ADDRESS' >&2
  exit 2
fi
target=$1
[[ -s nextcloud-calendar/manifest.json && -x nextcloud-calendar/backend/entry ]] || {
  echo 'Run install.sh from an extracted release archive.' >&2; exit 1;
}
command -v ssh >/dev/null
command -v scp >/dev/null
command -v tar >/dev/null
ssh "$target" 'test "$(uname -m)" = armv7l && test "$(id -u)" = 0 && test -f /home/root/xovi/extensions.d/appload.so' || {
  echo 'Requires an ARMv7 reMarkable 2, root SSH access and working AppLoad.' >&2; exit 1;
}
local_stage=$(mktemp -d)
trap 'rm -rf -- "$local_stage"' EXIT
tar -czf "$local_stage/app.tar.gz" nextcloud-calendar
remote_stage=$(ssh "$target" 'mktemp -d /home/root/calendar-install.XXXXXX')
[[ "$remote_stage" == /home/root/calendar-install.* && "$remote_stage" != *$'\n'* ]] || {
  echo 'Could not create a safe tablet staging directory.' >&2; exit 1;
}
scp "$local_stage/app.tar.gz" "$target:$remote_stage/app.tar.gz"
# The directory was generated by mktemp above, not supplied by a command-line option.
ssh "$target" sh -s -- "$remote_stage" <<'REMOTE'
set -eu
stage=$1
case "$stage" in /home/root/calendar-install.*) ;; *) exit 2 ;; esac
for entry_pid in $(pidof entry 2>/dev/null || true); do
  case "$(readlink /proc/$entry_pid/exe)" in
    */nextcloud-calendar/backend/entry)
      echo 'Close Nextcloud Calendar on the tablet, then run the installer again.' >&2
      exit 1 ;;
  esac
done
root=/home/root/xovi/exthome/appload
backup=/home/root/.local/share/nextcloud-calendar/backups/$(date +%Y%m%d-%H%M%S)-install
mkdir -p "$root" "$backup"
chmod 700 "$backup"
tar -xzf "$stage/app.tar.gz" -C "$stage"
app="$stage/nextcloud-calendar"
test -s "$app/manifest.json"
test -s "$app/resources.rcc"
test -s "$app/icon.png"
test -s "$app/backend/entry"
chmod 755 "$app/backend/entry"
if [ -f /home/root/.local/share/nextcloud-calendar/state.json ]; then
  cp -p /home/root/.local/share/nextcloud-calendar/state.json "$backup/state.json"
fi
if [ -d "$root/nextcloud-calendar" ]; then
  mv "$root/nextcloud-calendar" "$backup/bundle"
fi
if ! mv "$app" "$root/nextcloud-calendar"; then
  if [ -d "$backup/bundle" ]; then mv "$backup/bundle" "$root/nextcloud-calendar"; fi
  exit 1
fi
# AppLoad resolves icon symlinks; a versioned target avoids its old image-cache URL.
icon_target="icon-$(date +%Y%m%d-%H%M%S).png"
mv "$root/nextcloud-calendar/icon.png" "$root/nextcloud-calendar/$icon_target"
ln -s "$icon_target" "$root/nextcloud-calendar/icon.png"
rm -f "$stage/app.tar.gz"
rmdir "$stage"
printf 'Installed Nextcloud Calendar. Backup: %s\n' "$backup"
printf 'Close other AppLoad apps, tap AppLoad Reload, then open Nextcloud Calendar.\n'
REMOTE
